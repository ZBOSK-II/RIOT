/**
 * @file
 * @brief   Host-side ML-DSA-44 key, signature and header generator
 *
 * Built from the same PQClean sources as the firmware, so keys and
 * signatures are interchangeable with the board by construction.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "api.h"

#define PK_BYTES  PQCLEAN_MLDSA44_CLEAN_CRYPTO_PUBLICKEYBYTES
#define SK_BYTES  PQCLEAN_MLDSA44_CLEAN_CRYPTO_SECRETKEYBYTES
#define SIG_BYTES PQCLEAN_MLDSA44_CLEAN_CRYPTO_BYTES
#define MAX_MSG   (64 * 1024)

static int _read_file(const char *path, uint8_t *buf, size_t len, size_t *out_len, int exact)
{
    FILE *f = fopen(path, "rb");
    if (f == NULL) {
        perror(path);
        return -1;
    }
    size_t n = fread(buf, 1, len, f);
    int more = (fgetc(f) != EOF);
    fclose(f);
    if (exact && ((n != len) || more)) {
        fprintf(stderr, "%s: expected exactly %zu bytes\n", path, len);
        return -1;
    }
    if (!exact && more) {
        fprintf(stderr, "%s: larger than %zu bytes\n", path, len);
        return -1;
    }
    if (out_len != NULL) {
        *out_len = n;
    }
    return 0;
}

static int _write_file(const char *path, const uint8_t *buf, size_t len)
{
    FILE *f = fopen(path, "wb");
    if (f == NULL) {
        perror(path);
        return -1;
    }
    int ok = (fwrite(buf, 1, len, f) == len);
    fclose(f);
    if (!ok) {
        fprintf(stderr, "%s: short write\n", path);
        return -1;
    }
    return 0;
}

static void _write_array(FILE *f, const char *name, const uint8_t *buf, size_t len)
{
    fprintf(f, "static const uint8_t %s[%zu] = {", name, len);
    for (size_t i = 0; i < len; i++) {
        fprintf(f, "%s0x%02x,", (i % 12 == 0) ? "\n    " : " ", buf[i]);
    }
    fprintf(f, "\n};\n");
}

static FILE *_open_header(const char *path, const char *brief)
{
    FILE *f = fopen(path, "w");
    if (f == NULL) {
        perror(path);
        return NULL;
    }
    fprintf(f,
            "/*\n"
            " * SPDX-FileCopyrightText: 2026 Matvii Ivashchenko\n"
            " * SPDX-License-Identifier: LGPL-2.1-only\n"
            " */\n"
            "\n"
            "#pragma once\n"
            "\n"
            "/**\n"
            " * @ingroup     examples\n"
            " * @{\n"
            " *\n"
            " * @file\n"
            " * @brief       %s\n"
            " *\n"
            " * Generated by host/mldsa_tool, do not edit.\n"
            " *\n"
            " * @author      Matvii Ivashchenko\n"
            " */\n"
            "\n"
            "#include <stdint.h>\n"
            "\n"
            "#ifdef __cplusplus\n"
            "extern \"C\" {\n"
            "#endif\n"
            "\n",
            brief);
    return f;
}

static void _close_header(FILE *f)
{
    fprintf(f, "\n"
               "#ifdef __cplusplus\n"
               "}\n"
               "#endif\n"
               "\n"
               "/** @} */\n");
    fclose(f);
}

static int _export_header(const char *path, const uint8_t *pk)
{
    FILE *f = _open_header(path, "ML-DSA-44 public key the server verifies against");
    if (f == NULL) {
        return -1;
    }
    fprintf(f, "/** @brief ML-DSA-44 public key */\n");
    _write_array(f, "mldsa_pk", pk, PK_BYTES);
    _close_header(f);
    printf("wrote %s\n", path);
    return 0;
}

static int _cmd_keygen(int argc, char **argv)
{
    static uint8_t pk[PK_BYTES];
    static uint8_t sk[SK_BYTES];

    if (argc < 4) {
        return 2;
    }
    if (PQCLEAN_MLDSA44_CLEAN_crypto_sign_keypair(pk, sk) != 0) {
        fprintf(stderr, "keypair failed\n");
        return 1;
    }
    if ((_write_file(argv[2], pk, PK_BYTES) != 0) || (_write_file(argv[3], sk, SK_BYTES) != 0)) {
        return 1;
    }
    printf("wrote %s (%d bytes) and %s (%d bytes)\n", argv[2], PK_BYTES, argv[3], SK_BYTES);
    if ((argc > 4) && (_export_header(argv[4], pk) != 0)) {
        return 1;
    }
    return 0;
}

static int _cmd_sign(int argc, char **argv)
{
    static uint8_t sk[SK_BYTES];
    static uint8_t msg[MAX_MSG];
    static uint8_t sig[SIG_BYTES];
    size_t msg_len = 0;
    size_t sig_len = 0;

    if (argc < 5) {
        return 2;
    }
    if ((_read_file(argv[2], sk, SK_BYTES, NULL, 1) != 0) ||
        (_read_file(argv[3], msg, sizeof(msg), &msg_len, 0) != 0)) {
        return 1;
    }
    if (PQCLEAN_MLDSA44_CLEAN_crypto_sign_signature(sig, &sig_len, msg, msg_len, sk) != 0) {
        fprintf(stderr, "sign failed\n");
        return 1;
    }
    if (_write_file(argv[4], sig, sig_len) != 0) {
        return 1;
    }
    printf("signed %zu bytes, wrote %s (%zu bytes)\n", msg_len, argv[4], sig_len);
    return 0;
}

static int _cmd_verify(int argc, char **argv)
{
    static uint8_t pk[PK_BYTES];
    static uint8_t msg[MAX_MSG];
    static uint8_t sig[SIG_BYTES];
    size_t msg_len = 0;

    if (argc < 5) {
        return 2;
    }
    if ((_read_file(argv[2], pk, PK_BYTES, NULL, 1) != 0) ||
        (_read_file(argv[3], msg, sizeof(msg), &msg_len, 0) != 0) ||
        (_read_file(argv[4], sig, SIG_BYTES, NULL, 1) != 0)) {
        return 1;
    }
    int res = PQCLEAN_MLDSA44_CLEAN_crypto_sign_verify(sig, SIG_BYTES, msg, msg_len, pk);
    puts((res == 0) ? "signature OK" : "signature INVALID");
    return (res == 0) ? 0 : 1;
}

static int _cmd_export_header(int argc, char **argv)
{
    static uint8_t pk[PK_BYTES];

    if (argc < 4) {
        return 2;
    }
    if (_read_file(argv[2], pk, PK_BYTES, NULL, 1) != 0) {
        return 1;
    }
    return (_export_header(argv[3], pk) == 0) ? 0 : 1;
}

static int _cmd_export_testvec(int argc, char **argv)
{
    static uint8_t sk[SK_BYTES];
    static uint8_t sig[SIG_BYTES];
    size_t sig_len = 0;

    if (argc < 5) {
        return 2;
    }
    const uint8_t *msg = (const uint8_t *)argv[3];
    size_t msg_len = strlen(argv[3]);

    if (_read_file(argv[2], sk, SK_BYTES, NULL, 1) != 0) {
        return 1;
    }
    if (PQCLEAN_MLDSA44_CLEAN_crypto_sign_signature(sig, &sig_len, msg, msg_len, sk) != 0) {
        fprintf(stderr, "sign failed\n");
        return 1;
    }
    FILE *f = _open_header(argv[4], "Known-good ML-DSA-44 message and signature for the self-test");
    if (f == NULL) {
        return 1;
    }
    fprintf(f, "/** @brief Length of the test message in bytes */\n");
    fprintf(f, "#define MLDSA_TEST_MSG_LEN  (%zuU)\n\n", msg_len);
    fprintf(f, "/** @brief Test message: \"%s\" */\n", argv[3]);
    _write_array(f, "mldsa_test_msg", msg, msg_len);
    fprintf(f, "\n/** @brief Signature of @ref mldsa_test_msg under the demo key */\n");
    _write_array(f, "mldsa_test_sig", sig, sig_len);
    _close_header(f);
    printf("wrote %s\n", argv[4]);
    return 0;
}

static void _usage(const char *prog)
{
    fprintf(stderr,
            "usage:\n"
            "  %s keygen <pk.bin> <sk.bin> [pubkey.h]\n"
            "  %s sign <sk.bin> <msg-file> <sig.bin>\n"
            "  %s verify <pk.bin> <msg-file> <sig.bin>\n"
            "  %s export-header <pk.bin> <pubkey.h>\n"
            "  %s export-testvec <sk.bin> <message> <testvec.h>\n",
            prog, prog, prog, prog, prog);
}

int main(int argc, char **argv)
{
    int res = 2;

    if (argc >= 2) {
        if (strcmp(argv[1], "keygen") == 0) {
            res = _cmd_keygen(argc, argv);
        }
        else if (strcmp(argv[1], "sign") == 0) {
            res = _cmd_sign(argc, argv);
        }
        else if (strcmp(argv[1], "verify") == 0) {
            res = _cmd_verify(argc, argv);
        }
        else if (strcmp(argv[1], "export-header") == 0) {
            res = _cmd_export_header(argc, argv);
        }
        else if (strcmp(argv[1], "export-testvec") == 0) {
            res = _cmd_export_testvec(argc, argv);
        }
    }
    if (res == 2) {
        _usage(argv[0]);
    }
    return res;
}
